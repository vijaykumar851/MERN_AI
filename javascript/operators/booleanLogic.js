// && it is called  and operator if both conditions are true it prints true
let hasKey = true;
let knowsCode = true;

let openDoor = hasKey && knowsCode; 
console.log(openDoor); 


// || it is called OR operator if any one conditions is true it prints true
let isWeekend = true;
let isHoliday = false;

let canRest = isWeekend || isHoliday; 
console.log(canRest); 


// ! it is called NOT operator it will return the opasite value if its true it will return false
let isRaining = false;

let goOutside = !isRaining; 
